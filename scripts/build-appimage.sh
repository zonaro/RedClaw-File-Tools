#!/usr/bin/env bash
# Build the RedClaw File Tools Flutter Linux application and a portable AppImage.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VERSION="${APP_VERSION:-$(TZ=America/Sao_Paulo date +'%y.%j.%H%M')}"
if [[ ! "$VERSION" =~ ^[0-9]{2}\.[0-9]{3}\.[0-9]{4}$ ]]; then
  echo "Expected YY.DDD.HHMM version, got: $VERSION" >&2
  exit 2
fi
export APP_VERSION="$VERSION"

command -v flutter >/dev/null 2>&1 || { echo "Flutter SDK not found" >&2; exit 1; }
command -v curl >/dev/null 2>&1 || { echo "curl not found" >&2; exit 1; }

echo "Building RedClaw File Tools $VERSION"
pushd "$ROOT/manager" >/dev/null
flutter config --enable-linux-desktop
# Generated native Linux scaffolding can be regenerated by any Flutter SDK.
# Existing lib/, pubspec.yaml and tests are kept intact.
flutter create --platforms=linux --project-name redclaw_file_tools --org br.com.redclaw .
flutter pub get
flutter analyze
flutter test
flutter build linux --release --dart-define="APP_VERSION=$VERSION"
popd >/dev/null

BUNDLE="$ROOT/manager/build/linux/x64/release/bundle"
[[ -x "$BUNDLE/redclaw_file_tools" ]] || { echo "Flutter Linux bundle missing" >&2; exit 1; }
APPDIR="$ROOT/build/AppDir"
OUTDIR="$ROOT/dist"
rm -rf "$APPDIR"
mkdir -p "$APPDIR/usr/bin" "$APPDIR/usr/share/redclaw-file-tools/backend" \
  "$APPDIR/usr/share/redclaw-file-tools/payload" "$OUTDIR"
cp -a "$BUNDLE/." "$APPDIR/usr/bin/"

for file in "$ROOT"/backend/*.py "$ROOT"/backend/catalog.json; do
  cp "$file" "$APPDIR/usr/share/redclaw-file-tools/backend/"
done
find "$ROOT" -maxdepth 1 -type f -name '*.py' -exec cp -t "$APPDIR/usr/share/redclaw-file-tools/payload/" {} +
for folder in media_core assets; do
  cp -a "$ROOT/$folder" "$APPDIR/usr/share/redclaw-file-tools/payload/"
done
for file in color_database.json comic-reader comic-reader.desktop nautilus-follow-run nautilus-follow-run.desktop; do
  if [[ -f "$ROOT/$file" ]]; then
    cp "$ROOT/$file" "$APPDIR/usr/share/redclaw-file-tools/payload/"
  fi
done
cp "$ROOT/scripts/redclaw-file-tools.desktop" "$APPDIR/redclaw-file-tools.desktop"
cp "$ROOT/assets/redclaw-file-tools.svg" "$APPDIR/redclaw-file-tools.svg"
ln -s redclaw-file-tools.svg "$APPDIR/.DirIcon"

cat > "$APPDIR/AppRun" <<'APPRUN'
#!/usr/bin/env bash
set -euo pipefail
APPDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export REDCLAW_BACKEND="$APPDIR/usr/share/redclaw-file-tools/backend/redclaw.py"
export REDCLAW_PAYLOAD="$APPDIR/usr/share/redclaw-file-tools/payload"
export LD_LIBRARY_PATH="$APPDIR/usr/bin/lib:${LD_LIBRARY_PATH:-}"
exec "$APPDIR/usr/bin/redclaw_file_tools" "$@"
APPRUN
chmod +x "$APPDIR/AppRun"

TOOLS="$ROOT/build/appimage-tools"
mkdir -p "$TOOLS"
fetch_tool() {
  local path="$1" url="$2"
  if [[ ! -f "$path" ]]; then
    curl --fail --location --retry 3 "$url" -o "$path"
  fi
  chmod +x "$path"
}
fetch_tool "$TOOLS/linuxdeploy" \
  "https://github.com/linuxdeploy/linuxdeploy/releases/download/continuous/linuxdeploy-x86_64.AppImage"
fetch_tool "$TOOLS/appimagetool" \
  "https://github.com/AppImage/appimagetool/releases/download/continuous/appimagetool-x86_64.AppImage"

# linuxdeploy collects system libraries into the AppDir. We invoke appimagetool
# separately to retain our custom AppRun and its runtime/payload environment.
APPIMAGE_EXTRACT_AND_RUN=1 "$TOOLS/linuxdeploy" --appdir "$APPDIR" \
  --executable "$APPDIR/usr/bin/redclaw_file_tools" \
  --desktop-file "$ROOT/scripts/redclaw-file-tools.desktop" \
  --icon-file "$ROOT/assets/redclaw-file-tools.svg"

# linuxdeploy may generate its own launcher; restore our explicit environment.
cat > "$APPDIR/AppRun" <<'APPRUN'
#!/usr/bin/env bash
set -euo pipefail
APPDIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export REDCLAW_BACKEND="$APPDIR/usr/share/redclaw-file-tools/backend/redclaw.py"
export REDCLAW_PAYLOAD="$APPDIR/usr/share/redclaw-file-tools/payload"
export LD_LIBRARY_PATH="$APPDIR/usr/bin/lib:$APPDIR/usr/lib:${LD_LIBRARY_PATH:-}"
exec "$APPDIR/usr/bin/redclaw_file_tools" "$@"
APPRUN
chmod +x "$APPDIR/AppRun"

OUTPUT="$OUTDIR/RedClaw_File_Tools-${VERSION}-x86_64.AppImage"
ARCH=x86_64 APPIMAGE_EXTRACT_AND_RUN=1 VERSION="$VERSION" "$TOOLS/appimagetool" "$APPDIR" "$OUTPUT"
chmod +x "$OUTPUT"
(cd "$OUTDIR" && sha256sum "$(basename "$OUTPUT")" > "$(basename "$OUTPUT").sha256")
echo "AppImage created: $OUTPUT"
